import contextlib
import hashlib
import importlib.util
import io
import json
import os
import subprocess
import sys
import tempfile
import unittest
from datetime import datetime, timezone
from unittest import mock

_p = os.path.join(os.path.dirname(__file__), "..", "ops", "graphify", "graph_first.py")
_s = importlib.util.spec_from_file_location("graph_first", _p)
gf = importlib.util.module_from_spec(_s)
_s.loader.exec_module(gf)

HEADER = "Generated by `ops/runtime-map/collect.py` on 2026-10-29T10:51:48+07:00; regenerate with `make runtime-map`\n"


class Fixed(datetime):
    @classmethod
    def now(cls, tz=None):
        return datetime(2026, 10, 31, 9, 0, tzinfo=timezone.utc)


class GraphFirst(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.root = tmp.name

    def write(self, rel, body):
        path = os.path.join(self.root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(body)
        return path

    def build(self, *rels):
        """graph.json plus a manifest as graphify's full build writes it: mtime and the content MD5 in both hashes."""
        rows = {}
        for rel in rels:
            path = os.path.join(self.root, rel)
            with open(path, "rb") as f:
                h = hashlib.md5(f.read()).hexdigest()
            rows[rel] = {"mtime": os.stat(path).st_mtime, "ast_hash": h, "semantic_hash": h}
        self.write("graphify-out/graph.json", "{}")
        self.write("graphify-out/manifest.json", json.dumps(rows))
        return rows

    def context(self):
        out = io.StringIO()
        with mock.patch.dict(os.environ, {"CLAUDE_PROJECT_DIR": self.root}), contextlib.redirect_stdout(out):
            gf.main()
        return json.loads(out.getvalue())["hookSpecificOutput"]["additionalContext"] if out.getvalue() else ""

    def test_silent_without_a_graph(self):
        self.write("svc/a.py", "x = 1\n")
        self.assertEqual(self.context(), "")

    def test_current_graph_gives_the_map_only(self):
        self.write("svc/a.py", "x = 1\n")
        self.write("docs/a.md", "# a\n")
        self.build("svc/a.py", "docs/a.md")
        ctx = self.context()
        self.assertIn('graphify query "<question>"', ctx)
        self.assertIn("graphify-out/GRAPH_REPORT.md", ctx)
        self.assertIn("--graph ~/.graphify/repos/NousResearch/hermes-agent-v0.22.5/graphify-out/graph.json", ctx)
        self.assertIn("docs/runtime/README.md (missing: make runtime-map)", ctx)
        self.assertNotIn("behind", ctx)

    def test_fresh_checkout_mtimes_are_not_changes(self):
        a = self.write("svc/a.py", "x = 1\n")
        d = self.write("docs/a.md", "# a\n")
        self.build("svc/a.py", "docs/a.md")
        for path in (a, d):
            os.utime(path, (1, 1))   # git checkout: new mtime, same bytes
        self.assertEqual(gf.behind(self.root), [])

    def test_reports_edited_deleted_new_and_unextracted(self):
        for rel in ("svc/a.py", "svc/b.py", "docs/x.md", "docs/gone.md"):
            self.write(rel, f"# {rel}\n")
        rows = self.build("svc/a.py", "svc/b.py", "docs/x.md", "docs/gone.md")
        rows["docs/x.md"]["semantic_hash"] = ""   # graphify update ran after the doc changed: AST only
        self.write("graphify-out/manifest.json", json.dumps(rows))
        os.remove(os.path.join(self.root, "docs/gone.md"))
        os.utime(self.write("svc/b.py", "y = 2\n"), (1, 1))
        self.write("svc/new.py", "z = 3\n")
        self.assertEqual(gf.behind(self.root),
                         ["docs/gone.md (deleted)", "docs/x.md (not re-extracted)", "svc/b.py", "svc/new.py (new)"])
        self.assertIn("Graph is behind the working tree (4)", self.context())

    def test_new_files_skip_ignored_sensitive_and_unindexed_kinds(self):
        self.write("svc/a.py", "x = 1\n")
        self.build("svc/a.py")
        self.write(".graphifyignore", "# kept out\nsvc/ignored.py\nbuild/\n")
        self.write(".gitignore", "secrets/*.dec*\n")
        for rel in ("svc/ignored.py", "build/out.py", "svc/token_store.py", "secrets/x.dec.py", ".venv/lib.py",
                    "svc/__pycache__/a.py", "svc/notes.md", "svc/data.csv"):
            self.write(rel, "q = 1\n")
        self.assertEqual(gf.behind(self.root), [])   # .md and .csv: no such kind in this manifest

    def test_snapshot_age_from_the_runtime_header(self):
        self.write("docs/runtime/README.md", HEADER)
        with mock.patch.object(gf, "datetime", Fixed):
            got = gf.snapshot(self.root)
        self.assertEqual(got, ", collected 2026-10-29 10:51 WIB (2 days ago; refresh with make runtime-map)")

    def test_a_broken_map_never_fails_the_prompt(self):
        self.write("graphify-out/graph.json", "{}")
        self.write("graphify-out/manifest.json", "{not json")
        env = dict(os.environ, CLAUDE_PROJECT_DIR=self.root)
        p = subprocess.run([sys.executable, "-I", _p], input="{}", capture_output=True, text=True, env=env, timeout=30)
        self.assertEqual(p.returncode, 0)
        self.assertIn("Project map first", json.loads(p.stdout)["hookSpecificOutput"]["additionalContext"])


if __name__ == "__main__":
    unittest.main()
